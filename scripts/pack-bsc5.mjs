// Packs the Yale Bright Star Catalogue, 5th revised edition (Hoffleit and Warren 1991), into
// src/gpu/stars/bsc5.generated.ts for `real-sky` (story 2.6): 6 bytes a star, base64, so the
// catalogue travels in the effect's lazy chunk and works in the browser and under Node alike.
//
//   node scripts/pack-bsc5.mjs path/to/bsc5.dat
//
// The catalogue's fixed-width records (its ReadMe, byte positions from 1): HR 1-4, J2000 right
// ascension 76-83 (h m s), declination 84-90 (sign d m s), V magnitude 103-107, B-V 110-114.
// Records with no position (14 of them: novae and entries since withdrawn) are left out.
//
// Each star packed as little-endian:
//   u16  right ascension, J2000, as a share of 24 h times 65 536
//   i16  declination, J2000, as degrees times 364 (±90° in ±32 760)
//   u8   V magnitude, (V + 2) times 25, clamped (−1.46 to 8 in steps of 0.04)
//   i8   B−V, times 50, clamped to ±2.5 (127 when the catalogue has none)
// Sorted brightest first, so drawing the first n stars draws the n brightest.

import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';

const file = process.argv[2];
if (!file) throw new Error('usage: node scripts/pack-bsc5.mjs path/to/bsc5.dat');
const stars = [];
for (const line of readFileSync(file, 'latin1').split('\n')) {
  if (line.length < 114 || line.slice(75, 77).trim() === '') continue;
  const ra =
    (Number(line.slice(75, 77)) +
      Number(line.slice(77, 79)) / 60 +
      Number(line.slice(79, 83)) / 3600) /
    24;
  const sign = line[83] === '-' ? -1 : 1;
  const dec =
    sign *
    (Number(line.slice(84, 86)) +
      Number(line.slice(86, 88)) / 60 +
      Number(line.slice(88, 90)) / 3600);
  const v = Number(line.slice(102, 107));
  const bvText = line.slice(109, 114).trim();
  const bv = bvText === '' ? NaN : Number(bvText);
  if (!Number.isFinite(v)) continue;
  stars.push({ ra, dec, v, bv });
}
stars.sort((a, b) => a.v - b.v);
const bytes = new Uint8Array(stars.length * 6);
const view = new DataView(bytes.buffer);
stars.forEach((s, i) => {
  view.setUint16(i * 6, Math.round(s.ra * 65536) % 65536, true);
  view.setInt16(i * 6 + 2, Math.round(s.dec * 364), true);
  view.setUint8(i * 6 + 4, Math.max(0, Math.min(255, Math.round((s.v + 2) * 25))));
  view.setInt8(
    i * 6 + 5,
    Number.isFinite(s.bv) ? Math.max(-125, Math.min(125, Math.round(s.bv * 50))) : 127,
  );
});
const base64 = Buffer.from(bytes).toString('base64');
const source = `// Generated by scripts/pack-bsc5.mjs from the Yale Bright Star Catalogue, 5th revised edition
// (Hoffleit and Warren 1991), as distributed by the Harvard-Smithsonian Center for Astrophysics.
// Do not edit by hand. See src/gpu/stars/catalogue.ts for the layout.

/** Stars packed, brightest first. */
export const BSC5_COUNT = ${stars.length};
export const BSC5 = '${base64}';
`;
writeFileSync(
  'src/gpu/stars/bsc5.generated.ts',
  await format(source, { parser: 'typescript', printWidth: 100000 }),
);
console.log(
  `packed ${stars.length} stars, ${bytes.length} bytes, ${base64.length} base64 characters`,
);
